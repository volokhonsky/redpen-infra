"""Виды замечаний и их прежние имена.

`major` (крупный маркер, основной разбор) и `minor` (обычное замечание) — так
вид называется с переименования сущности 2026-08-29. До него те же два значения
назывались `main` и `comment`, а третье, `general` (замечание ко всей странице
без привязки к точке), было упразднено ещё раньше.

Таблица перевода была скопирована в четырёх местах — в API, в генераторе
страниц, в конвертере markdown и в разовом мигрирующем скрипте. Здесь она в
одном экземпляре.

Приём старых значений остаётся **навсегда**, а не до фазы 6: markdown-черновики
и журнал ревизий писались годами, они неизменяемы, и читать их придётся всегда.
"""

from typing import Dict

#: Прежнее имя -> текущее.
LEGACY_KINDS: Dict[str, str] = {"main": "major", "comment": "minor"}

#: Текущее имя -> прежнее. Нужно ровно одному потребителю: `render_page()`,
#: вход оптимистической блокировки, заморожен в прежних именах навсегда —
#: сдвиг хеша страницы выдал бы 409 всем открытым сессиям редактора.
LEGACY_KIND_NAMES: Dict[str, str] = {v: k for k, v in LEGACY_KINDS.items()}

KINDS = ("major", "minor")


def to_current(kind: str) -> str:
    """Текущее имя вида. `general` показываем как обычное замечание."""
    if kind in LEGACY_KINDS:
        return LEGACY_KINDS[kind]
    return "minor" if kind == "general" else kind
